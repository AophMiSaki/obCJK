static const int kDikTableCount = sizeof(kDikTable) / sizeof(kDikTable[0]);

static UInt16 ParseHotkey(const char* str, UInt16 def)
{
    if (!str || !str[0]) return def;
    if (_strnicmp(str, "DIK_", 4) == 0) {
        for (int i = 0; i < kDikTableCount; i++)
            if (_stricmp(str, kDikTable[i].name) == 0) return kDikTable[i].code;
        return def;
    }
    unsigned int v = 0;
    bool anyDigit = false;
    const char* p = str;
    if (p[0] == '0' && (p[1] == 'x' || p[1] == 'X')) {
        p += 2;
        if (!*p) return def;
        for (; *p; p++) {
            if      (*p >= '0' && *p <= '9') { v = v * 16 + (*p - '0'); anyDigit = true; }
            else if (*p >= 'a' && *p <= 'f') { v = v * 16 + (*p - 'a' + 10); anyDigit = true; }
            else if (*p >= 'A' && *p <= 'F') { v = v * 16 + (*p - 'A' + 10); anyDigit = true; }
            else break;
        }
    } else {
        if (!*p) return def;
        for (; *p; p++) {
            if (*p >= '0' && *p <= '9') { v = v * 10 + (*p - '0'); anyDigit = true; }
            else break;
        }
    }
    if (!anyDigit) return def;
    UInt16 code = (UInt16)v;
    if (code == 0x00) return 0x00;
    for (int i = 0; i < kDikTableCount; i++)
        if (kDikTable[i].code == code) return code;
    return def;
}

static UInt8 ParseGamepadButton(const char* str, UInt8 def)
{
    if (!str || !str[0]) return def;
    unsigned int v = 0;
    bool anyDigit = false;
    for (const char* p = str; *p; p++) {
        if (*p >= '0' && *p <= '9') { v = v * 10 + (*p - '0'); anyDigit = true; }
        else break;
    }
    if (!anyDigit || v > 0xFF) return def;
    return (UInt8)v;
}

// Keyboard hotkey modifier: 0=None, 1=Ctrl, 2=Shift。手把binding不使用這個欄位
// （組合鍵binding有自己獨立的 comboModifierButton，見 HotkeySettings）。
static UInt8 ParseHotkeyModifier(const char* str, UInt8 def)
{
    if (!str || !str[0])            return def;
    if (_stricmp(str, "None")  == 0) return 0;
    if (_stricmp(str, "Ctrl")  == 0) return 1;
    if (_stricmp(str, "Shift") == 0) return 2;
    return def;
}

// GamepadHold 專用: 按住秒數(可含小數，如"1.5")。限制在0.1~10秒之間，避免
// ini被手動改壞成0(瞬間觸發，等同沒有長按判斷)或超大值(事實上永遠按不到)。
// 不用strtof——跟本檔其餘Parse*函式一致，手刻逐字元解析,不依賴CRT locale。
static float ParseHotkeyHoldSeconds(const char* str, float def)
{
    if (!str || !str[0]) return def;
    float whole = 0.0f, frac = 0.0f, fracDiv = 1.0f;
    bool anyDigit = false, inFrac = false;
    for (const char* p = str; *p; p++) {
        if (*p == '.' && !inFrac) { inFrac = true; continue; }
        if (*p < '0' || *p > '9') break;
        anyDigit = true;
        if (!inFrac) whole = whole * 10.0f + (*p - '0');
        else { fracDiv *= 10.0f; frac += (*p - '0') / fracDiv; }
    }
    if (!anyDigit) return def;
    float v = whole + frac;
    if (v < 0.1f) v = 0.1f;
    if (v > 10.0f) v = 10.0f;
    return v;
}

// 一組熱鍵(Editor或Ime)的完整設定 — 鍵盤/手把長按/手把組合鍵 3 組互不排斥的
// 獨立binding，可以同時生效(見 main.cpp IsHotkeyDown())，不再是舊版「三選一」
// 的Device欄位。每組binding各自有Disabled旗標(對應obCJK_iniEdit.py
// MultiHotkeyCapture的3個「停用」勾選框)；allDisabled是總開關(對應「全部
// 停用」勾選框)，開啟時這組熱鍵(Editor或Ime)不論哪個裝置都不會觸發。
// holdStartTick是執行期狀態(不是ini設定，每次GetTickCount()更新)，只有
// holdDisabled==false時才有意義，見 obCJK_Gamepad.h IsGamepadButtonHeldFor()。
struct HotkeySettings {
    // 鍵盤binding
    UInt16 kbdCode;
    UInt8  kbdModifier;           // 0=None,1=Ctrl,2=Shift
    bool   kbdDisabled;

    // 手把長按鍵binding：單一按鍵連續按住超過holdSeconds秒才觸發
    UInt8  holdButton;
    float  holdSeconds;
    bool   holdDisabled;
    DWORD  holdStartTick;         // 執行期狀態，非ini

    // 手把組合鍵binding：修飾鍵(左)held+主鍵(右)held同時成立才觸發
    UInt8  comboButton;           // 主鍵(右)
    UInt8  comboModifierButton;   // 修飾鍵(左)
    bool   comboDisabled;

    // 總開關：開啟時這組熱鍵(不分裝置)一律不觸發
    bool   allDisabled;
};
